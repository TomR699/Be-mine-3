/**
 * Build text as one merged mesh, centred on the origin, facing +Z.
 *
 *   cell   size of one pixel of the font, in world units
 *   depth  how far the letters stand off their backing
 */
export function makeText(text, { cell = 0.1, depth = 0.06, color = 0xffffff,
                                 emissive = null } = {}) {
  const chars = text.toUpperCase().split('');
  const advance = 6;                       // 5 wide plus a column of space
  const totalW = (chars.length * advance - 1) * cell;

  const pos = [], nrm = [], idx = [];
  const box = new THREE.BoxGeometry(cell, cell, depth);
  const boxPos = box.attributes.position.array;
  const boxNrm = box.attributes.normal.array;
  const boxIdx = box.index.array;

  let cursor = -totalW / 2;
  for (const ch of chars) {
    const glyph = FONT[ch];
    if (!glyph) { cursor += advance * cell; continue; }

    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (!(glyph[row] & (1 << (4 - col)))) continue;
        const ox = cursor + col * cell;
        const oy = (6 - row) * cell;        // row 0 is the top
        const base = pos.length / 3;
        for (let i = 0; i < boxPos.length; i += 3) {
          pos.push(boxPos[i] + ox, boxPos[i + 1] + oy, boxPos[i + 2]);
          nrm.push(boxNrm[i], boxNrm[i + 1], boxNrm[i + 2]);
        }
        for (let i = 0; i < boxIdx.length; i++) idx.push(base + boxIdx[i]);
      }
    }
    cursor += advance * cell;
  }
  box.dispose();

  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  geo.setAttribute('normal', new THREE.Float32BufferAttribute(nrm, 3));
  geo.setIndex(idx);
  geo.computeBoundingSphere();

  const mat = new THREE.MeshLambertMaterial({ color });
  if (emissive) mat.emissive = new THREE.Color(emissive);

  const mesh = new THREE.Mesh(geo, mat);
  mesh.castShadow = true;
  return mesh;
}

/** Width the text will occupy, for laying out whatever sits behind it. */
export function textWidth(text, cell = 0.1) {
  return (text.length * 6 - 1) * cell;
}
